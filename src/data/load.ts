const cache = new Map<FormatId, Promise<FormatData>>()

async function load(format: FormatId): Promise<FormatData> {
  const src = SOURCES[format]!
  const [files, cards] = await Promise.all([Promise.all(Object.values(src.decks).map((l) => l())), src.cards()])
  const bySeason = new Map(files.map((f) => [f.season, f.decks]))
  const seasons: SeasonWithDecks[] = src.seasons
    .map((s, i) => ({
      ...s,
      end: src.seasons[i + 1]?.start,
      decks: (bySeason.get(s.id) ?? []).slice().sort((a, b) => a.tier - b.tier || deckScore(b) - deckScore(a)),
    }))
    .filter((s) => s.decks.length > 0)
  return { seasons, cards }
}

export function loadFormat(format: FormatId): Promise<FormatData> | null {
  if (!SOURCES[format]) return null
  if (!cache.has(format)) cache.set(format, load(format))
  return cache.get(format)!
}

export function findDeck(data: FormatData, id: string): { deck: Deck; season: SeasonWithDecks } | undefined {
  for (const season of data.seasons) {
    const deck = season.decks.find((d) => d.id === id)
    if (deck) return { deck, season }
  }
  return undefined
}
