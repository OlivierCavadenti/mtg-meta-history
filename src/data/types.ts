export type FormatId = 'standard' | 'pioneer' | 'modern' | 'legacy' | 'vintage' | 'pauper' | 'premodern' | 'limited'

export type Archetype = 'aggro' | 'midrange' | 'control' | 'combo' | 'tempo' | 'ramp'

export type L10n = { fr: string; en: string }

/** [count, card name] */
export type CardLine = [number, string]

export type CardKind =
  | 'creature'
  | 'planeswalker'
  | 'battle'
  | 'instant'
  | 'sorcery'
  | 'artifact'
  | 'enchantment'
  | 'land'
  | 'other'

/** Compact card record generated from Scryfall data. */
export type CardInfo = {
  /** mana cost, Scryfall notation: "{1}{B}" */
  m: string
  /** mana value */
  c: number
  t: CardKind
  /** colors, WUBRG letters */
  k: string
  /** Scryfall image id: printing of the era the card was first played in */
  i: string
  /** season id -> Scryfall image id, for later seasons where a newer printing existed */
  e?: Record<string, string>
  /** newest regular printing overall (no Universes Beyond reprint), when different from `i` */
  n?: string
}

export type DeckList = {
  main: CardLine[]
  side: CardLine[]
  player: string
  event: string
  rank: string
  date: string
  /** mtgtop8 deck page */
  url: string
}

export type Deck = {
  id: string
  name: string
  season: string
  archetype: Archetype
  colors: string
  /** 1 = deck to beat, 2 = top tier, 3 = solid performer */
  tier: 1 | 2 | 3
  /** first and last recorded result in the season (ISO dates) */
  first: string
  last: string
  /** counts from mtgtop8 high-level events in the season (Limited: drafts and share of games) */
  stats: { results: number; top8: number; wins: number; share: number }
  /** Limited only: 17Lands public data for the color combination in the set's Premier Draft */
  limited?: LimitedStats
  /** Limited before 17Lands data (2011-2020): a design archetype, no list or numbers; its sources */
  sources?: string[]
  summary: L10n
  why: { fr: string[]; en: string[] }
  keyCards: string[]
  cover: string
  list: DeckList
}

export type LimitedStats = {
  games: number
  /** game win rate, % */
  winRate: number
  drafts: number
  /** 7-win runs */
  trophies: number
  /** average game win rate of the set's 17Lands players, % */
  setWinRate: number
}

export type Ban = { date: string; cards: string[] }

export type Season = {
  id: string
  /** ISO date of the season-opening set release */
  start: string
  /** first set of the season */
  set: string
  bans: Ban[]
  /** Limited: the set code; the season is named after its set instead of its years */
  code?: string
  /** Limited: 17Lands sample of the set */
  source?: { games: number; drafts: number; winRate: number; url: string }
}

/** end = start of the following season (undefined for the current one) */
export type SeasonWithDecks = Season & { end?: string; decks: Deck[] }

export type FormatData = {
  seasons: SeasonWithDecks[]
  cards: Record<string, CardInfo>
}

/** Every result of every deck of a season (generated by build.py, loaded by the deck page only). */
export type ResultsFile = {
  season: string
  /** mtgtop8 format code, for deck URLs */
  code: string
  /** event key -> [event name, ISO date] */
  events: Record<string, [string, string]>
  /** deck id -> its results by date: [event key, result id (mtgtop8 deck id), rank ('' when not a finish), player, period source URL?] */
  decks: Record<string, ResultRow[]>
  /** deck id -> result id of its sample list */
  rep: Record<string, number | string>
}

export type ResultRow = [string, number | string, string, string] | [string, number | string, string, string, string]

/** Lists of a season's results, for the "All decklists" modal (generated by build.py). */
export type ListsFile = {
  season: string
  names: string[]
  /** card data of names missing from the format's cards.json */
  info: Record<string, CardInfo>
  /** result id -> [main, side], each a flat [count, name index, count, name index, ...] array */
  lists: Record<string, [number[], number[]]>
}

/** Current price of each card of a format (generated by prices.py from Scryfall's daily bulk data). */
export type PriceFile = {
  /** ISO date of the Scryfall data */
  date: string | null
  /** card name -> [EUR, USD]: cheapest tournament-legal paper printing, any finish */
  cards: Record<string, [number | null, number | null]>
}
